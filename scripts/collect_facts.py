#!/usr/bin/env python3
"""
collect_facts.py - gather every number the paper cites into one traceable dictionary.

The paper is generated by substituting these values into a prose template. No figure in
the paper is typed by hand, so no figure can drift from the data that produced it. Each
entry records the file it came from, so any claim can be traced back to a run.

Output: paper/facts.json
"""

import csv
import json
import os
import statistics as st
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
R = lambda *p: os.path.join(ROOT, *p)

facts = {}
prov = {}


def put(key, value, source):
    facts[key] = value
    prov[key] = source


def jload(path):
    with open(path, encoding="utf-8-sig") as fh:
        return json.load(fh)


def cload(path):
    with open(path, encoding="utf-8-sig") as fh:
        return list(csv.DictReader(fh))


def f(x, n=3):
    return round(float(x), n)


# ---------------------------------------------------------------- environment
put("host_cpu", "Intel Core i7-10700 (8 cores / 16 threads, 2.90 GHz base)", "docs/environment.md")
put("host_ram_gb", 32, "docs/environment.md")
put("host_os", "Windows 11 Pro, build 26200.9168", "docs/environment.md")
put("node_version", "24.15.0", "docs/environment.md")
put("k6_version", "2.2.0", "docs/environment.md")
put("dataset_bytes", 88826, "sut/data/content.json")
put("dataset_records", 188, "sut/data/content.json")

# ---------------------------------------------------------------- smoke
p = R("results", "smoke", "metrics.json")
if os.path.exists(p):
    m = jload(p)
    put("smoke_requests", m["requests"], p)
    put("smoke_mean", f(m["mean_ms"]), p)
    put("smoke_p99", f(m["p99_ms"]), p)
    put("smoke_p99_raw", f(m["p99_raw_ms"]), p)
    put("smoke_p99_quant", f(m["p99_quantized_ms"]), p)
    put("smoke_bias", f(m["quantization_bias_ms"]), p)

# ---------------------------------------------------------------- calibration
p = R("results", "calibration", "sweep.csv")
if os.path.exists(p):
    rows = [r for r in cload(p) if r.get("p50_ms")]
    put("calib_levels", len(rows), p)
    put("calib_max_vus", max(int(r["vus"]) for r in rows), p)
    put("calib_peak_rps", int(max(float(r["rps"]) for r in rows)), p)
    put("calib_cores_plateau", f(st.median([float(r["cores_used"]) for r in rows if int(r["vus"]) >= 8]), 2), p)
    by = {int(r["vus"]): r for r in rows}
    for v in (1, 2, 4, 8, 16, 200):
        if v in by:
            put(f"calib_p50_{v}", f(by[v]["p50_ms"], 2), p)
            put(f"calib_p99_{v}", f(by[v]["p99_ms"], 2), p)
            put(f"calib_rps_{v}", int(float(by[v]["rps"])), p)
            put(f"calib_ratio_{v}", f(float(by[v]["p99_ms"]) / float(by[v]["p50_ms"]), 2), p)

# ---------------------------------------------------------------- Arm A matrix
p = R("results", "matrix", "aggregate.json")
if os.path.exists(p):
    a = jload(p)
    put("matrix_runs_total", a["rows_total"], p)
    put("matrix_runs_failed", a["rows_failed"], p)
    put("matrix_warmups_discarded", a["warmup_runs_discarded"], p)
    for c in a["cells"]:
        slug = c["route"].strip("/").replace("/", "_").replace(".", "_")
        k = f"arma_{slug}_v{c['vus']}"
        put(k + "_mean", f(c["avg_ms_mean"]), p)
        put(k + "_p50", f(c["p50_ms_mean"]), p)
        put(k + "_p95", f(c["p95_ms_mean"]), p)
        put(k + "_p99", f(c["p99_ms_mean"]), p)
        put(k + "_ratio", f(c["p99_over_mean"], 2), p)
        put(k + "_rps", int(c["rps_mean"]), p)

# ---------------------------------------------------------------- stress
for tag, d in (("stress_a", "stress"), ("stress_b", "stress_b")):
    p = R("results", d, "summary.json")
    if os.path.exists(p):
        s = jload(p)
        put(f"{tag}_requests", s["requests"], p)
        put(f"{tag}_rps", int(s["rps_achieved"]), p)
        put(f"{tag}_dropped", s["dropped_iterations"], p)
        put(f"{tag}_failed_pct", f(s["failed_rate"] * 100, 3), p)
        put(f"{tag}_transport_err", s["err_transport"], p)
        put(f"{tag}_5xx", s["err_5xx"], p)
        put(f"{tag}_p50", f(s["p50"], 1), p)
        put(f"{tag}_p99", f(s["p99"], 1), p)
    p2 = R("results", d, "server_proc.csv")
    if os.path.exists(p2):
        rows = [r for r in cload(p2) if r.get("rss_mb")]
        if rows:
            rss = [float(r["rss_mb"]) for r in rows]
            h = [int(r["handles"]) for r in rows if r.get("handles", "").isdigit()]
            put(f"{tag}_rss_start", f(rss[0], 0), p2)
            put(f"{tag}_rss_peak", f(max(rss), 0), p2)
            if h:
                put(f"{tag}_handles_start", h[0], p2)
                put(f"{tag}_handles_peak", max(h), p2)

# ---------------------------------------------------------------- soak
p = R("results", "soak", "metrics.json")
if os.path.exists(p):
    m = jload(p)
    put("soak_requests", m["requests"], p)
    put("soak_span_s", int(m["wall_span_s"]), p)
    put("soak_rps", int(m["throughput_rps"]), p)
    put("soak_errors_pct", f(m["error_rate_pct"], 4), p)
    put("soak_mean", f(m["mean_ms"]), p)
    put("soak_p50", f(m["p50_ms"]), p)
    put("soak_p95", f(m["p95_ms"]), p)
    put("soak_p99", f(m["p99_ms"]), p)
    put("soak_p999", f(m["p99_9_ms"]), p)
    put("soak_ratio", f(m["p99_over_mean"], 2), p)
    put("soak_early_p95", f(m["early_p95_ms"]), p)
    put("soak_late_p95", f(m["late_p95_ms"]), p)
    put("soak_degradation", f(m["degradation_ratio_p95"], 4), p)
    put("soak_degradation_pct", f(m["degradation_pct_p95"], 2), p)
    put("soak_mw_p", m["mannwhitney_p"], p)
    put("soak_effect_r", f(m["effect_size_r"], 4), p)
    put("soak_p99_raw", f(m["p99_raw_ms"]), p)
    put("soak_p99_quant", f(m["p99_quantized_ms"]), p)
    put("soak_bias", f(m["quantization_bias_ms"]), p)
p2 = R("results", "soak", "server_proc.csv")
if os.path.exists(p2):
    rows = [r for r in cload(p2) if r.get("rss_mb")]
    rss = [float(r["rss_mb"]) for r in rows]
    q = len(rss) // 4
    put("soak_rss_quarters", [f(sum(rss[i * q:(i + 1) * q]) / q, 1) for i in range(4)], p2)

# ---------------------------------------------------------------- scaled arm
p = R("results", "scaled_merged", "aggregate.json")
if not os.path.exists(p):
    p = R("results", "scaled", "aggregate.json")
if os.path.exists(p):
    a = jload(p)
    for c in a["cells"]:
        scale = c["tag"]
        slug = c["route"].strip("/").replace("/", "_").replace(".", "_")
        k = f"scaled_{scale}_{slug}"
        put(k + "_mean", f(c["avg_ms_mean"], 2), p)
        put(k + "_p50", f(c["p50_ms_mean"], 2), p)
        put(k + "_p99", f(c["p99_ms_mean"], 2), p)
        put(k + "_ratio", f(c["p99_over_mean"], 2), p)
        put(k + "_rps", int(c["rps_mean"]), p)
        put(k + "_n", c["runs_kept"], p)

# ---------------------------------------------------------------- Arm B
for mode in ("disabled", "enabled"):
    d = R("results", "armb", mode)
    if not os.path.isdir(d):
        continue
    runs = []
    for fn in sorted(os.listdir(d)):
        if fn.startswith("run") and fn.endswith(".json"):
            n = int(fn[3:-5])
            if n == 1:
                continue          # warm-up discarded
            runs.append(jload(os.path.join(d, fn)))
    if runs:
        put(f"armb_{mode}_n", len(runs), d)
        put(f"armb_{mode}_mean", f(st.mean(r["avg"] for r in runs)), d)
        put(f"armb_{mode}_p50", f(st.mean(r["p50"] for r in runs)), d)
        put(f"armb_{mode}_p99", f(st.mean(r["p99"] for r in runs)), d)
        put(f"armb_{mode}_rps", int(st.mean(r["rps"] for r in runs)), d)
        put(f"armb_{mode}_failed_pct", f(st.mean(r["failed_rate"] for r in runs) * 100, 3), d)

# ---------------------------------------------------------------- Arm C
p = R("results", "mixed", "index.csv")
if os.path.exists(p):
    rows = [r for r in cload(p) if r.get("status") == "OK" and r.get("is_warmup") == "false"]
    byname = {}
    for r in rows:
        byname.setdefault(r["name"], []).append(r)
    for name, rs in byname.items():
        put(f"armc_{name}_n", len(rs), p)
        put(f"armc_{name}_mean", f(st.mean(float(r["mean_ms"]) for r in rs)), p)
        put(f"armc_{name}_p50", f(st.mean(float(r["p50_ms"]) for r in rs)), p)
        put(f"armc_{name}_p95", f(st.mean(float(r["p95_ms"]) for r in rs)), p)
        put(f"armc_{name}_p99", f(st.mean(float(r["p99_ms"]) for r in rs)), p)
        put(f"armc_{name}_ratio", f(st.mean(float(r["p99_over_mean"]) for r in rs), 2), p)
        put(f"armc_{name}_rps", int(st.mean(float(r["rps"]) for r in rs)), p)

# ------------------------------------------------- Arm C percentile ladder
p = R("results", "mixed", "percentile_ladder.json")
if os.path.exists(p):
    for row in jload(p):
        k = "ladder_" + row["name"]
        put(k + "_n", int(row["n"]), p)
        for stat in ("mean", "p50", "p90", "p95", "p99", "p999", "p9999", "max", "cv"):
            put(f"{k}_{stat}", f(row[stat], 3), p)
        put(k + "_frac_over_3ms", f(row["frac_over_3ms"], 3), p)

# ---------------------------------------------------------------- Arm E
p = R("results", "open", "index.csv")
if os.path.exists(p):
    rows = [r for r in cload(p) if r.get("status") == "OK" and r.get("is_warmup") == "false"]
    byrate = {}
    for r in rows:
        byrate.setdefault(int(r["target_rate"]), []).append(r)
    for rate, rs in byrate.items():
        put(f"arme_{rate}_n", len(rs), p)
        put(f"arme_{rate}_achieved", int(st.mean(float(r["achieved_rps"]) for r in rs)), p)
        put(f"arme_{rate}_dropped", int(st.mean(float(r["dropped_iterations"]) for r in rs)), p)
        put(f"arme_{rate}_mean", f(st.mean(float(r["mean_ms"]) for r in rs)), p)
        put(f"arme_{rate}_p95", f(st.mean(float(r["p95_ms"]) for r in rs)), p)
        put(f"arme_{rate}_p99", f(st.mean(float(r["p99_ms"]) for r in rs)), p)

# ---------------------------------------------------------------- totals
# Summed from actual run records - never estimated.
total_requests = 0
total_sources = []
for idx, col in (
    (R("results", "matrix", "index.csv"), "requests"),
    (R("results", "scaled", "index.csv"), "requests"),
    (R("results", "scaled_extra", "index.csv"), "requests"),
    (R("results", "mixed", "index.csv"), "requests"),
    (R("results", "open", "index.csv"), "requests"),
):
    if os.path.exists(idx):
        for r in cload(idx):
            v = (r.get(col) or "").strip()
            if v.isdigit():
                total_requests += int(v)
        total_sources.append(idx)
for d in ("smoke", "soak", "stress", "stress_b"):
    p_ = R("results", d, "summary.json")
    if os.path.exists(p_):
        try:
            total_requests += int(jload(p_)["requests"])
            total_sources.append(p_)
        except Exception:
            pass
for mode in ("disabled", "enabled"):
    d_ = R("results", "armb", mode)
    if os.path.isdir(d_):
        for fn in os.listdir(d_):
            if fn.startswith("run") and fn.endswith(".json"):
                try:
                    total_requests += int(jload(os.path.join(d_, fn))["requests"])
                except Exception:
                    pass
        total_sources.append(d_)
for idx in (R("results", "calibration", "sweep.csv"),):
    if os.path.exists(idx):
        for r in cload(idx):
            v = (r.get("requests") or "").strip()
            if v.isdigit():
                total_requests += int(v)
        total_sources.append(idx)
put("total_requests", total_requests, "; ".join(total_sources))

# ---------------------------------------------------------------- write
out = R("paper", "facts.json")
os.makedirs(os.path.dirname(out), exist_ok=True)
with open(out, "w", encoding="utf-8") as fh:
    json.dump({"facts": facts, "provenance": prov}, fh, indent=2)

print(f"collected {len(facts)} facts -> {out}")
missing = [k for k, v in facts.items() if v is None]
if missing:
    print("  NULL values:", missing)
groups = {}
for k in facts:
    groups[k.split("_")[0]] = groups.get(k.split("_")[0], 0) + 1
for g, n in sorted(groups.items()):
    print(f"  {g:<12} {n}")
